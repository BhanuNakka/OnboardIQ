import { Router } from 'express';
import { authenticate } from '../middleware/auth.middleware.js';
import { allowRoles } from '../middleware/role.middleware.js';
import { uploadDocument } from '../middleware/upload.middleware.js';
import { authorizeCustomerUpload } from '../middleware/documentAccess.middleware.js';
import { asyncHandler } from '../utils/http.js';
import * as applications from '../controllers/application.controller.js';
import * as documents from '../controllers/document.controller.js';
const router = Router(); router.use(authenticate);
router.post('/', allowRoles('CUSTOMER'), asyncHandler(applications.createApplication));
router.get('/mine', allowRoles('CUSTOMER'), asyncHandler(applications.mine));
router.get('/', allowRoles('MAKER', 'CHECKER', 'COMPLIANCE', 'ADMIN'), asyncHandler(applications.listAll));
router.get('/:applicationId/documents', allowRoles('CUSTOMER', 'MAKER', 'CHECKER', 'COMPLIANCE', 'ADMIN'), asyncHandler(applications.listDocuments));
router.post('/:applicationId/documents', allowRoles('CUSTOMER'), authorizeCustomerUpload, uploadDocument, asyncHandler(documents.upload));
router.post('/:applicationId/submit', allowRoles('CUSTOMER'), asyncHandler(applications.submit));
router.post('/:applicationId/evaluate', allowRoles('ADMIN'), asyncHandler(applications.evaluate));
router.get('/:applicationId/decision', allowRoles('CUSTOMER', 'MAKER', 'CHECKER', 'COMPLIANCE', 'ADMIN'), asyncHandler(applications.getDecision));
router.get('/:applicationId/extractions', allowRoles('MAKER', 'CHECKER', 'COMPLIANCE', 'ADMIN'), asyncHandler(documents.listExtractions));
router.get('/:applicationId', allowRoles('CUSTOMER', 'MAKER', 'CHECKER', 'COMPLIANCE', 'ADMIN'), asyncHandler(applications.getOne));
router.patch('/:applicationId', allowRoles('CUSTOMER'), asyncHandler(applications.patchOne));
export default router;
